"""Table 2 of the paper (dataset statistics), from the released dataset.

Reads the release: participants.tsv, derivatives/vikitraj (manifest.tsv, labels2d/, keypoints2d/, tracks3d/), the
VICON and iPad motion files, the frame size of every video clip and the size of every file.
Writes outputs/paper/tables/dataset_stats.tex.

    python paper/dataset_stats.py [--release release/ViKi-Traj]
"""
import argparse
import json
from pathlib import Path

import cv2
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TAB = ROOT / "outputs" / "paper" / "tables"
VIEWS = ("top", "side")

# visit videos (not released): top / side count and minutes, from align_videos.py (video_alignment_summary_all.csv)
VISIT_VIDEOS, VISIT_MIN = (57, 59), 502


def n_lines(path):
    with open(path, "rb") as f:
        return sum(1 for _ in f)


def fmt_int(n):
    return f"{int(n):,}".replace(",", "{,}")


def size_gb(files):
    s = sum(f.stat().st_size for f in files) / 1e9
    return f"{s:.2f} GB" if s < 1 else f"{s:.1f} GB"


def sidecar(root, motion):
    """The _motion.json of a _motion.tsv given relative to the release root."""
    return json.loads((root / motion.replace("_motion.tsv", "_motion.json")).read_text())


def vicon_samples(path):
    """Rows of a VICON motion file with at least one marker (rows outside the recording are n/a)."""
    x = pd.read_csv(path, sep="\t", header=None, na_values="n/a").to_numpy()
    return int((~np.isnan(x)).any(axis=1).sum())


def clip_sizes(root, m):
    """Frame size of every clip from its MP4 header: participant_id, session, view, width, height."""
    rows = []
    for view in VIEWS:
        for r in m[m[f"{view}_video"].notna()].itertuples():
            cap = cv2.VideoCapture(str(root / getattr(r, f"{view}_video")))
            rows.append((r.participant_id, r.session, view, int(cap.get(cv2.CAP_PROP_FRAME_WIDTH)),
                         int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))))
            cap.release()
    return pd.DataFrame(rows, columns=["participant_id", "session", "view", "width", "height"])


def write_table(path, sections):
    lines = ["% generated by paper/dataset_stats.py", "\\begin{tabular}{@{}ll@{}}", "\\toprule"]
    for i, (title, rows) in enumerate(sections):
        lines += (["\\midrule"] if i else []) + [f"\\multicolumn{{2}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\"]
        lines += [f"{a} & {b} \\\\" for a, b in rows]
    lines += ["\\bottomrule", "\\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--release", type=Path, default=ROOT / "release" / "ViKi-Traj", help="root of the released dataset")
    root = ap.parse_args().release
    der = root / "derivatives" / "vikitraj"
    m = pd.read_csv(der / "manifest.tsv", sep="\t", na_values="n/a")
    part = pd.read_csv(root / "participants.tsv", sep="\t")
    n = len(m)

    per_pid = m.groupby("participant_id").size()
    span = f"{per_pid.min()}" if per_pid.min() == per_pid.max() else f"{per_pid.min()}--{per_pid.max()}"
    q = m.movement_time.quantile([.5, .25, .75])
    n_td, n_ucp = (part.group == "TD").sum(), (part.group == "UCP").sum()
    trials = [("Participants (TD / UCP)", f"{len(part)} ({n_td} / {n_ucp})"),
              ("Trials (per participant)", f"{n} ({span})"),
              ("Trial duration: median [IQR]", f"{q[.5]:.1f} [{q[.25]:.1f}--{q[.75]:.1f}] s")]

    vicon, ipad = m.vicon_motion.dropna(), m.ipad_motion.dropna()
    meta = [sidecar(root, f) for f in vicon]
    (n_markers,) = {j["TrackedPointsCount"] for j in meta}             # one value over all VICON files
    (vicon_hz,) = {j["SamplingFrequency"] for j in meta}
    n_vicon = sum(vicon_samples(root / f) for f in vicon)
    ipad_hz = np.median([sidecar(root, f)["SamplingFrequencyEffective"] for f in ipad])
    n_ipad = sum(n_lines(root / f) for f in ipad)                     # no header row
    sizes = clip_sizes(root, m)
    w, h = sizes.groupby(["width", "height"]).size().idxmax()
    fps = round(pd.concat([m.top_fps, m.side_fps]).median())
    streams = [("VICON: markers, rate, samples", f"{n_markers}, {vicon_hz} Hz, {fmt_int(n_vicon)}"),
               ("End-effector: rate, samples", f"$\\approx${round(ipad_hz)} Hz, {fmt_int(n_ipad)}"),
               ("Video (top, side): rate, size", f"{fps} Hz, {w}$\\times${h}$^{{*}}$"),
               ("Video clips (top / side)", " / ".join(str(m[f"{v}_video"].notna().sum()) for v in VIEWS)),
               ("Video frames (top / side)", " / ".join(fmt_int(m[f"{v}_n_frames"].sum()) for v in VIEWS)),
               ("Visit videos (V1/V2)", f"{VISIT_VIDEOS[0]} / {VISIT_VIDEOS[1]}, {VISIT_MIN} min")]

    n_label_frames = sum(n_lines(root / f) - 1 for v in VIEWS for f in m[f"{v}_labels"].dropna())
    n_models = sum(d.is_dir() for d in (der / "keypoints2d").iterdir())
    n_kp = len(list((der / "keypoints2d").rglob("*_keypoints.tsv")))
    n_tracks = len(list((der / "tracks3d").rglob("*_tracks3d.tsv")))
    labels = [("2D labels: clips, frames",
               " / ".join(str(m[f"{v}_labels"].notna().sum()) for v in VIEWS) + f", {fmt_int(n_label_frames)}"),
              ("Model keypoints: models, files", f"{n_models}, {fmt_int(n_kp)}"),
              ("3D tracks: files", f"{n_tracks}")]

    files = [f.relative_to(root) for f in root.rglob("*") if f.is_file()]
    groups = [("Motion, events, behavioral", lambda f: f.parts[0].startswith("sub-")),
              ("End-effector trajectory", lambda f: f.parts[:2] == ("sourcedata", "trajectory")),
              ("VICON recordings (C3D)", lambda f: f.parts[:2] == ("sourcedata", "vicon") and f.suffix == ".c3d"),
              ("Video clips", lambda f: f.parts[:2] == ("sourcedata", "videos")),
              ("Derivatives", lambda f: f.parts[0] == "derivatives"),
              ("Total", lambda f: True)]
    release_files = []
    for name, keep in groups:
        sel = [root / f for f in files if keep(f)]
        release_files.append((name, f"{fmt_int(len(sel))} ({size_gb(sel)})"))

    TAB.mkdir(parents=True, exist_ok=True)
    out = TAB / "dataset_stats.tex"
    write_table(out, [("Participants and trials", trials), ("Trials Data streams", streams),
                      ("Labels and benchmark data", labels), ("Dataset files (size)", release_files)])
    print("wrote", out)


if __name__ == "__main__":
    main()
